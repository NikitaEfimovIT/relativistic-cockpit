const ALIGNED = Math.cos((5 * Math.PI) / 180) // the nose within 5° of the mark on the glass: choice
/** By a body, the nose along the motion relative to it (sign 1), or against it (−1), as the marks on the glass show. */
const isNoseAlong = (s: SimState, sign: 1 | -1): boolean => {
  if (!s.local || s.local.centre === null) return false
  const v = s.local.v
  const speed = Math.hypot(v[0], v[1], v[2])
  const f = forwardOf(s.course.attitude)
  return speed > 1 && (sign * (f[0] * v[0] + f[1] * v[1] + f[2] * v[2])) / speed >= ALIGNED
}
const isFed = (s: SimState): boolean => s.propulsion.pressurised && s.propulsion.feedOpen

