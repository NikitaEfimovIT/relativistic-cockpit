/** A step of a procedure, and whether the ship shows it done: the desk ticks it by itself. */
export interface Step {
  readonly text: string
  readonly isDone: (s: SimState) => boolean
}

/** A fault's procedure, or with no fault a checklist for a manoeuvre. */
export interface Procedure {
  readonly fault?: FaultId
  readonly title: string
  readonly steps: readonly Step[]
}

export interface ManualPage {
  readonly title: string
  readonly text: readonly string[]
  readonly procedures?: readonly Procedure[]
}

