/** Which steps the desk ticks: done, and every step before done too, so that a checklist is ticked off in order. */
export const ticksOf = (procedure: Procedure, s: SimState): readonly boolean[] =>
  procedure.steps.reduce<boolean[]>((ticks, step, i) => [...ticks, (i === 0 || ticks[i - 1]) && step.isDone(s)], [])

/** A page's procedures, those of the faults open now first: the desk's key for a fault opens the page at its top. */
export const proceduresInOrder = (page: ManualPage, s: SimState): readonly Procedure[] => {
  const isOpen = (p: Procedure): boolean => p.fault !== undefined && activeFaults(s.habitat).includes(p.fault)
  const procedures = page.procedures ?? []
  return [...procedures.filter(isOpen), ...procedures.filter((p) => !isOpen(p))]
}

