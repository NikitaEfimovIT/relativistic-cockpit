"""
The cockpit, built from nothing so that it can be rebuilt at will.

  /Applications/Blender.app/Contents/MacOS/Blender --background --factory-startup \
      --python blender/cockpit.py -- [--dry] [--fast] [--views pilot_lit,pilot_dark,hero,outside,side]

--dry builds, saves cockpit.blend and exports cockpit.glb with its triangle count, and renders nothing. --fast renders
at a quarter of the cost, for checking a change. The parts are in cockpit_lib/.

Axes as in the app once exported to glTF: Blender +Y is forward (glTF −Z), +Z is up, metres, and the pilot's eye is at
the origin. Every control, screen and lamp hangs on a named empty (ctl_*, scr_*, lamps_*, gauge_*, annunciator) that
the app will find by name; legends, the pictures on the screens, the outside of the ship and the mannequin exist only
for the renders.
"""

import math
import os
import sys

import bpy

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from cockpit_lib import cabin, console, couch, dash, exterior, furniture, panel, quarters, shape, stage, walkmap, wallpanel  # noqa: E402  (needs the path above)
from cockpit_lib.geometry import collection  # noqa: E402
from cockpit_lib.materials import make_materials  # noqa: E402

PROJECT = os.path.dirname(HERE)
GLB = os.path.join(PROJECT, 'public', 'cockpit.glb')
LAYOUT = os.path.join(PROJECT, 'src', 'cockpitLayout.ts')


def to_app(point) -> str:
    """Blender (x, y forward, z up) to the app's (x, y up, z aft), as glTF does it."""
    x, y, z = point
    return f'[{x:.4f}, {z:.4f}, {-y:.4f}]'


def hull_area() -> float:
    """The outer skin's area from the aft wall to the nose: perimeters of the grown section, summed along the hull."""
    step = 0.05
    total = 0.0
    for i in range(round((shape.NOSE - shape.TAIL) / step)):
        ring = shape.section(shape.TAIL + (i + 0.5) * step, shape.SKIN, to_keel=True)
        total += sum(math.dist(a, b) for a, b in zip(ring, ring[1:] + ring[:1])) * step
    return total


def write_layout() -> None:
    """The few numbers the app's physics needs from the shape, so that it and the model never disagree."""
    foot, anchor = cabin.fob_anchor()
    lines = [
        '// Generated by blender/cockpit.py from the shape in blender/cockpit_lib/shape.py. Do not edit by hand.',
        walkmap.IMPORT,
        '',
        '/** m³ in the tub below the sills and under the canopy above them, before the furniture takes its share. */',
        f'export const CABIN_VOLUME = {shape.cabin_volume():.3f}',
        '/** m² of the outer skin round the volume the crew lives in, from the aft wall to the nose: what loses its heat to space. */',
        f'export const HULL_AREA = {hull_area():.1f}',
        '/** m, eye at 0: the lowest the canopy sill comes, at its front end, and the top of the glass. */',
        f'export const CANOPY_SILL_LOW = {shape.lowest_canopy_sill():.4f}',
        f'export const CANOPY_CROWN = {shape.CROWN:.4f}',
        '/** m aft of the eye: the partition at the cockpit door. Aft of it the shutters close off nothing that is in view. */',
        f'export const COCKPIT_DOOR_Z = {-shape.DOOR_Y:.3f}',
        '/** Where the fob\'s bracket meets the canopy bow, and where its cord hangs from (app axes: x right, y up, z aft). */',
        f'export const FOB_BRACKET = {to_app(foot)} as const',
        f'export const FOB_ANCHOR = {to_app(anchor)} as const',
        '',
        *walkmap.lines(),
    ]
    with open(LAYOUT, 'w', encoding='utf-8') as out:
        out.write('\n'.join(lines))


def main() -> None:
    args = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
    views = args[args.index('--views') + 1].split(',') if '--views' in args else list(stage.VIEWS)
    shape.check()
    stage.reset_scene()
    mats = make_materials()
    cabin.build_shell(mats)
    quarters.build_quarters(mats)
    exterior.build_exterior(mats)
    furniture.build_furniture(mats)
    wallpanel.build_door(mats)
    console.build_console(mats)
    console.build_room_panel(mats)
    panel.build_panel(mats)
    dash.build_dash(mats)
    cabin.build_consoles(mats)
    couch.build_couch(mats)
    couch.build_mannequin(mats)
    stage.build_lights()
    cameras = stage.build_cameras()
    collection('placeholders').objects.link(bpy.data.objects.new('seat_eye', None))
    stage.setup_render('--fast' in args)
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(HERE, 'cockpit.blend'))
    stage.export_glb(GLB)
    write_layout()
    if '--dry' in args:
        print('BUILT', len(bpy.data.objects), 'objects')
        return
    stage.render_views(views, cameras, mats, os.path.join(HERE, 'renders'))


main()
