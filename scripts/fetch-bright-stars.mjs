// Fetches the naked-eye sky from the Hipparcos catalogue and writes src/brightStars.json.
//
//   node scripts/fetch-bright-stars.mjs
//
// Positions, V and B−V from the Hipparcos main catalogue (ESA 1997, VizieR I/239), parallaxes from its new reduction
// (van Leeuwen 2007, VizieR I/311), joined by HIP number. Queried from the VizieR mirror at the CfA, which answers when
// the one at the CDS does not.

import { writeFile } from 'node:fs/promises'

const VIZIER = 'https://vizier.cfa.harvard.edu/viz-bin/asu-tsv'
const V_LIMIT = 6.5 // the naked-eye limit of the Bright Star Catalogue
const HP_LIMIT = 8 // the new reduction is selected by Hp; this is wide enough to hold every star with V < 6.5
const OUT = new URL('../src/brightStars.json', import.meta.url)

async function query(source, columns, constraint) {
  const url = `${VIZIER}?-source=${source}&-out=${columns.join(',')}&${constraint}&-out.max=unlimited`
  const response = await fetch(url)
  if (!response.ok) throw new Error(`VizieR answered ${response.status} for ${source}`)
  const lines = (await response.text()).split('\n').filter((line) => line.trim() && !line.startsWith('#'))
  const header = lines[0].split('\t').map((name) => name.trim())
  if (header.join() !== columns.join()) throw new Error(`Unexpected columns from ${source}: ${header.join()}`)
  // After the header come a line of units and a line of dashes
  return lines.slice(3).map((line) => Object.fromEntries(line.split('\t').map((cell, i) => [columns[i], cell.trim()])))
}

const number = (text) => (text === '' ? null : Number(text))

const main = await query('I/239/hip_main', ['HIP', 'RAICRS', 'DEICRS', 'Vmag', 'B-V', 'Plx', 'e_Plx'], `Vmag=%3C${V_LIMIT}`)
const reduced = new Map((await query('I/311/hip2', ['HIP', 'Plx', 'e_Plx'], `Hpmag=%3C${HP_LIMIT}`)).map((row) => [row.HIP, row]))

const stars = main
  .filter((row) => row.RAICRS !== '' && row.DEICRS !== '')
  .map((row) => {
    const better = reduced.get(row.HIP)
    const plx = number(better ? better.Plx : row.Plx)
    const ePlx = number(better ? better.e_Plx : row.e_Plx)
    return [Number(row.HIP), Number(Number(row.RAICRS).toFixed(5)), Number(Number(row.DEICRS).toFixed(5)), Number(row.Vmag), number(row['B-V']), plx, ePlx]
  })

const missingReduction = main.filter((row) => !reduced.has(row.HIP)).length
await writeFile(OUT, JSON.stringify({
  about: 'Hipparcos stars brighter than V 6.5. Positions, V, B−V: ESA 1997 (VizieR I/239). Parallaxes: van Leeuwen 2007 (VizieR I/311) '
    + 'where it has the star, else ESA 1997. Generated by scripts/fetch-bright-stars.mjs.',
  columns: ['hip', 'ra', 'dec', 'v', 'bv', 'plx', 'ePlx'],
  stars,
}) + '\n')
console.log(`${stars.length} stars written; ${missingReduction} without the 2007 parallax, kept with the 1997 one`)
